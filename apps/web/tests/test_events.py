def test_command_card() -> None:
    """<command-*> は順不同でも1枚のカードにまとまる（03 §3 の実物例）．"""
    text = (
        "<command-message>caveman:caveman</command-message>\n"
        "            <command-name>/caveman:caveman</command-name>"
    )
    plain, events = sessions.analyze_special(text)
    assert plain == ""
    assert len(events) == 1  # 複数のタグでも1枚
    ev = events[0]
    assert ev["event_type"] == "command"
    assert ev["title"] == "Command /caveman:caveman"
    assert ev["status"] == "info"
    assert ev["detail"] == "/caveman:caveman"

    # 引数があるケース（名前と引数を1行に）
    text2 = (
        "<command-name>/plugin</command-name>\n"
        "<command-message>plugin</command-message>\n"
        "<command-args>list --enabled</command-args>"
    )
    _, events2 = sessions.analyze_special(text2)
    assert len(events2) == 1
    assert events2[0]["title"] == "Command /plugin list --enabled"


