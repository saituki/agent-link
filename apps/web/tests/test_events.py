def test_time_required_for_all_items() -> None:
    """timestamp の無い行は直前の項目の時刻で補われる（03 §2）．"""
    rows = [
        {
            "type": "assistant",
            "uuid": "a",
            "timestamp": "2026-09-23T01:00:00Z",
            "message": {"role": "assistant", "content": [{"type": "text", "text": "はじめ"}]},
        },
        # 時刻の無い行（実物にもまれにある）
        {"type": "user", "uuid": "b", "message": {"role": "user", "content": "途中の指示"}},
        {
            "type": "assistant",
            "uuid": "c",
            "timestamp": "2026-09-23T01:02:00Z",
            "message": {"role": "assistant", "content": [{"type": "text", "text": "おわり"}]},
        },
    ]
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "sample.jsonl"
        path.write_text(
            "\n".join(json.dumps(r, ensure_ascii=False) for r in rows) + "\n",
            encoding="utf-8",
        )
        items, _cursor = sessions.read_conversation("claude", path)
        times = [i.get("time") for i in items]
        assert times[0] == "2026-09-23T01:00:00Z"
        assert times[1] == "2026-09-23T01:00:00Z"  # 直前の項目の時刻を使う
        assert times[2] == "2026-09-23T01:02:00Z"
        assert all(t for t in times)  # 全項目に時刻が付く


