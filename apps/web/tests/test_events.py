def test_hidden_tags() -> None:
    """caveat と system-reminder は表示しない（03 §3）．"""
    caveat = (
        "<local-command-caveat>Caveat: The messages below were generated by the user "
        "while running local commands.</local-command-caveat>"
    )
    plain, events = sessions.analyze_special(caveat)
    assert plain == ""
    assert events == []

    reminder = "<system-reminder>\nSessionStart:startup hook success: PONYTAIL MODE ACTIVE\n</system-reminder>"
    plain, events = sessions.analyze_special(reminder)
    assert plain == ""
    assert events == []

    # 本文の後ろに付いた system-reminder も，文は残っても出さない
    text = "今日の天気は晴れです\n\n" + reminder
    plain, events = sessions.analyze_special(text)
    assert "晴れ" in plain
    assert "PONYTAIL" not in plain
    assert "system-reminder" not in plain
    assert events == []


